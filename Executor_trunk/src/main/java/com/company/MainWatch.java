            sb.append("\"sandbox_backend\":")
                    .append(secureSandbox && sandboxRunner != null ? jsonString(sandboxRunner.describe())
                            : (precompiledDispatch && precompiledRunner != null
                                    ? jsonString(precompiledRunner.describe()) : "null"))
                    .append(',');
            sb.append("\"results_v2_write_counts\":{");
