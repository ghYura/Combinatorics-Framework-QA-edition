    /** Run up to K ISOLATED invocations of a candidate's main() through the SAME compile/reflect path,
     *  mirroring py_executor.measure_metric_repeated. Each repeat gets a FRESH compiled class (fresh
     *  child classloader via withCompiledClass) so side effects / static state never leak between
     *  repeats. Sample 0 owns the canonical verdict; if it is an infrastructure failure, NO further
     *  side-effecting invocations are attempted (stop-on-canonical-failure). Each invocation harvests
     *  its raw app= line at its own repeat_idx (recorded repeat-aware); missing/failed are accounted by
     *  the caller from the returned list. */
    private static List<RepeatMeasurement> measureMetricRepeated(
            String res, String generatedClassName, String[] args, String candidateId,
            String candidateFileName, int k) {
        List<RepeatMeasurement> measurements = new ArrayList<>(k);
        for (int repeatIdx = 0; repeatIdx < k; repeatIdx++) {
            Path sink = prepareMetricSink(candidateId, repeatIdx);
            Outcome outcome = null;
            Integer verdict = null;
            try {
                verdict = withCompiledClass(res, generatedClassName, clz -> {
                    Method meth = clz.getMethod("main", String[].class);
                    meth.invoke(null, (Object) args);
                    return FW_CUSTOM_VARmode ? clz.getDeclaredField("FW_CUSTOM_VAR").getInt(null)
                                             : clz.getDeclaredField("FW_VAR").getInt(null);
                });
            } catch (Exception e) {
                outcome = classifyFailure(e);
            }
            String metricLine = readMetricSink(sink);
            recordSample(candidateId, candidateFileName, repeatIdx, repeatEnvId, true, metricLine);
            measurements.add(new RepeatMeasurement(outcome, verdict, metricLine));
            if (repeatIdx == 0 && outcome != null) break;   // stop-on-canonical-failure
        }
        return measurements;
    }

