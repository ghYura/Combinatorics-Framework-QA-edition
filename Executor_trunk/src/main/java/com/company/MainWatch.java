            sb.append("\"outcomes\":{");
            Outcome[] outcomeValues = Outcome.values();
            for (int i = 0; i < outcomeValues.length; i++) {
                if (i > 0) sb.append(',');
                sb.append(jsonString(outcomeValues[i].name())).append(':').append(outcomeCounts.get(outcomeValues[i]).get());
            }
            sb.append('}');
