    /** sha256 over the sorted candidate name list, one line at a time -- byte-for-byte
     *  what Reader's HandoffManifestWriter.sha256OfLines (and py_executor's
     *  _sources_dir_digest) produce: ``md.update((name + "\n").getBytes(UTF_8))`` per
     *  name, NOT a single "\n".join(...) (which drops the final newline). */
    private static String sha256OfLines(List<String> names) {
        try {
            java.security.MessageDigest md = java.security.MessageDigest.getInstance("SHA-256");
            for (String n : names) md.update((n + "\n").getBytes(StandardCharsets.UTF_8));
            byte[] digest = md.digest();
            StringBuilder sb = new StringBuilder(digest.length * 2);
            for (byte b : digest) sb.append(String.format("%02x", b));
            return sb.toString();
        } catch (java.security.NoSuchAlgorithmException e) {
            throw new IllegalStateException("SHA-256 unavailable", e);
        }
    }

