    private static void submitCandidateFile(Path candidatePath, CandidateMode mode) {
        if (!isJavaCandidatePath(candidatePath)) return;
        ensureCandidateExecutor();
        Path normalized = candidatePath.toAbsolutePath().normalize();
        if (!scheduledCandidateFiles.add(normalized)) return;
        try {
            candidateExecutor.execute(() -> {
                try {
                    if (waitForCandidateReady(normalized)) {
                        processCandidateFileByMode(normalized.toString(), mode);
                    }
                } catch (Throwable t) {
                    t.printStackTrace();
                } finally {
                    scheduledCandidateFiles.remove(normalized);
                }
            });
        } catch (RejectedExecutionException rejected) {
            scheduledCandidateFiles.remove(normalized);
            throw rejected;
        }
    }

