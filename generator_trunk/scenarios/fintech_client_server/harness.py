"""Finance stack client-server test — generated by testgen_fintech.py.
Exercises client→server1→server2 via:
  Phase 0  HTTP smoke  — real httpx call through server1 → server2 (TARGET_BASE_URL)
  Phase 1  Auth layer  — direct verify_request checks (HMAC security module)
  Phase 2  Domain layer — InMemory service (fast, no DB, full logic coverage)
  Phase 2b Sudden      — FW_Optional mid-flight surprises
  Phase 3  Workflow    — build_settlement_plan validation
  Phase 4  Invariants  — post-run assertions

TARGET_BASE_URL is patched by RunMeFirstOnce before each candidate runs,
routing the HTTP smoke to the correct one of the 4 app instances.

FW_VAR verdict codes (fwVar.shift=1, mode=FW_VAR):
  0  PASS
  2  unexpected crash / unhandled exception
  3  domain invariant violated
  4  HMAC security bypass
  5  currency normalisation failure
  6  wrong HTTP status / transaction status
"""
